public class Experiment {
    String id;
    String name;
    int mass;
    int rating;

    //Constructs an Experiment object with an ID, name, mass, and science rating.
    public Experiment(String id, String name, int mass, int rating) {
        this.id = id;
        this.name = name;
        this.mass = mass;
        this.rating = rating;
    }
      
  
}
